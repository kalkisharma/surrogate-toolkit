        f"Model type : linear (Ridge Regression)",
        f"sklearn    : {sklearn.__version__} (not required at prediction time)",
        "",
        "FILES",
        "  surrogate.py   — self-contained Python wrapper (only file you need)",
        "  README.txt     — this file",
        "",
        "PREDICTION EQUATION",
