        X_arr  = _coerce(X, _INPUT_COLUMNS)
        X_norm = _normalize(X_arr, _INPUT_COLUMNS, _NORM_PARAMS)
        return (X_norm @ _COEF.T) + _INTERCEPT  # (n_samples, n_outputs)

