# ── Shared normalization block embedded in every surrogate.py ─────────────────

_NORM_BLOCK = '''
def _coerce(X, input_columns):
    try:
        import pandas as pd
        if isinstance(X, pd.DataFrame):
            missing = [c for c in input_columns if c not in X.columns]
            if missing:
                raise ValueError(f"DataFrame missing columns: {missing}. Expected: {input_columns}")
            return X[input_columns].values.astype(float)
    except ImportError:
        pass
    arr = np.asarray(X, dtype=float)
    if arr.ndim == 1:
        arr = arr.reshape(1, -1)
    if arr.shape[1] != len(input_columns):
        raise ValueError(
            f"Expected {len(input_columns)} input columns, got {arr.shape[1]}. "
            f"Columns in order: {input_columns}"
        )
    return arr


def _normalize(X, columns, params):
    X_out = X.copy()
    for i, col in enumerate(columns):
        p = params.get(col)
        if not p:
            continue
        m = p.get("method", "none")
        if m == "minmax":
            rng = p["max"] - p["min"]
            X_out[:, i] = (X_out[:, i] - p["min"]) / rng if rng != 0 else 0.0
        elif m == "zscore":
            X_out[:, i] = (X_out[:, i] - p["mean"]) / p["std"] if p["std"] != 0 else 0.0
        elif m == "log":
            shift = p.get("shift", 0.0)
            X_out[:, i] = np.log10(np.clip(X_out[:, i] + shift, 1e-12, None))
    return X_out
'''

